-- Exact cloud schema applied to the Anshel Supabase project on 2026-11-11.
CREATE SCHEMA IF NOT EXISTS anshel;

CREATE TABLE anshel.setting (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE anshel.tasks (
  id text PRIMARY KEY,
  seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  request_id text UNIQUE,
  creator text NOT NULL,
  division text NOT NULL,
  project text NOT NULL,
  description text NOT NULL,
  kind text NOT NULL,
  priority integer NOT NULL CHECK (priority BETWEEN 0 AND 2),
  status text NOT NULL,
  urgent integer NOT NULL CHECK (urgent IN (0,1)),
  created bigint NOT NULL,
  started bigint,
  ended bigint,
  attempts integer NOT NULL DEFAULT 0,
  lease text,
  lease_until bigint,
  result text,
  sha256 text,
  error text
);

CREATE TABLE anshel.audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at bigint NOT NULL,
  task text REFERENCES anshel.tasks(id),
  actor text NOT NULL,
  action text NOT NULL,
  detail text NOT NULL
);

CREATE INDEX tasks_queue ON anshel.tasks (status, priority DESC, created, seq);
CREATE UNIQUE INDEX tasks_one_running_division ON anshel.tasks(division) WHERE status = 'running';
CREATE INDEX audit_latest ON anshel.audit (id DESC);

REVOKE ALL ON SCHEMA anshel FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA anshel FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA anshel FROM PUBLIC, anon, authenticated;

ALTER TABLE anshel.setting ENABLE ROW LEVEL SECURITY;
ALTER TABLE anshel.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE anshel.audit ENABLE ROW LEVEL SECURITY;
